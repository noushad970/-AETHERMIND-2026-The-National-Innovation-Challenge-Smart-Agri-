  static List<CropCatalogEntry> search(String query) {
    if (query.trim().isEmpty) return allCrops;
    final q = query.trim().toLowerCase();
    return allCrops.where((c) {
      return c.nameBn.toLowerCase().contains(q) ||
          c.nameEn.toLowerCase().contains(q) ||
          c.category.toLowerCase().contains(q) ||
          c.scientificName.toLowerCase().contains(q);
    }).toList();
  }

  static List<CropCatalogEntry> getByCategory(String category) {
    if (category == 'All' || category == 'সব') return allCrops;
    return allCrops.where((c) => c.category.toLowerCase() == category.toLowerCase()).toList();
  }
